function mix32(x){ x = (x ^ (x >>> 16)) >>> 0; x = Math.imul(x,0x7feb352d) >>> 0; x = (x ^ (x >>> 15)) >>> 0; x = Math.imul(x,0x846ca68b) >>> 0; return (x ^ (x >>> 16)) >>> 0; }
function pick(list,n,salt=0){ const seed=mix32((Number(n)||1) * 0x9e3779b1 + (salt+1) * 0x85ebca6b); return list[seed % list.length]; }
function creatorIdentity(n){
 const real=pick(CREATOR_NAMES,n,2), handle=pick(CREATOR_HANDLES,n,7);
 const serial=String(((n*73)%997)+1).padStart(3,'0');
 return `${real} / ${handle}-${serial}`;
}

